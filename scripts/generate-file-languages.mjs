/** Builds small metadata from installed grammars; no runtime grammar imports in Home. */
import { readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { bundledLanguagesInfo } from "shiki/langs";

const root = fileURLToPath(new URL("../", import.meta.url));
const definitions = path.join(root, "node_modules/monaco-editor/esm/vs/languages/definitions");
const monaco = [];
for (const directory of await readdir(definitions, { withFileTypes: true })) {
  if (!directory.isDirectory()) continue;
  const code = await readFile(path.join(definitions, directory.name, "register.js"), "utf8");
  for (const match of code.matchAll(/registerLanguage\(\{([\s\S]*?)\n\}\);/g)) {
    const registration = match[1];
    const id = registration.match(/id: "([^"]+)"/)?.[1];
    if (id === undefined) throw new Error(`Missing language id in ${directory.name}`);
    monaco.push({ id, directory: directory.name,
      extensions: readArray(registration, "extensions"), filenames: readArray(registration, "filenames") });
  }
}

const catalogue = [];
const configurations = [];
for (const info of bundledLanguagesInfo) {
  const module = await info.import();
  const grammar = module.default.find(value => value.name === info.id);
  const ids = [info.id, ...info.aliases ?? []];
  const builtIn = monaco.filter(value => ids.includes(value.id));
  if (builtIn.length > 0) {
    const directory = builtIn[0].directory;
    configurations.push(`  "${info.id}": () => import("monaco-editor/languages/definitions/${directory}/${directory}.js"),`);
  }
  const extensions = new Set(builtIn.flatMap(value => value.extensions));
  const filenames = new Set(builtIn.flatMap(value => value.filenames));
  for (const type of grammar?.fileTypes ?? []) {
    extensions.add(`.${type.replace(/^\./, "")}`);
    filenames.add(type);
  }
  // Some upstream grammars omit associations supplied by their VS Code extension.
  const extra = {
    jsx: [".jsx"], tsx: [".tsx"], mdx: [".mdx"], vue: [".vue"], svelte: [".svelte"],
    json: [".json"], jsonc: [".jsonc"], jsonl: [".jsonl", ".ndjson"],
    dotenv: [".env"], make: [".mk"], diff: [".diff", ".patch"],
    groovy: [".groovy", ".gradle"], hlsl: [".hlsl"], bibtex: [".bib"]
  };
  for (const extension of extra[info.id] ?? []) extensions.add(extension);
  const names = { dotenv: [".env"], make: ["Makefile", "GNUmakefile"], codeowners: ["CODEOWNERS"] };
  for (const filename of names[info.id] ?? []) filenames.add(filename);
  if (info.id === "just") filenames.add(".justfile");
  if (info.id === "javascript") extensions.delete(".jsx");
  if (info.id === "typescript") extensions.delete(".tsx");
  catalogue.push({ id: info.id, name: info.name, aliases: info.aliases ?? [],
    extensions: [...extensions].sort(), filenames: [...filenames].sort() });
}
const destination = path.join(root, "packages/opencodex-ui/src/features/fileLanguages/catalogue.json");
await writeFile(destination, `[\n${catalogue.map(value => `  ${JSON.stringify(value)}`).join(",\n")}\n]\n`);
const loaders = path.join(root, "packages/opencodex-ui/src/features/fileLanguages/configurationLoaders.ts");
await writeFile(loaders, `// Generated by scripts/generate-file-languages.mjs; do not edit manually.\nimport type { languages } from "monaco-editor/editor/editor.api";\n\n/** Lazy Monaco editing rules, independent of its Monarch tokenizers. */\nexport const configurationLoaders: Record<string, () => Promise<{ conf: languages.LanguageConfiguration }>> = {\n${configurations.join("\n")}\n};\n`);
console.log(`Generated ${catalogue.length} language definitions.`);

/** Extracts literal metadata arrays from Monaco's generated registrations. */
function readArray(code, field) {
  const match = code.match(new RegExp(`${field}: \\[([^\\]]*)\\]`));
  if (match === null) return [];
  return [...match[1].matchAll(/"([^"]+)"/g)].map(value => value[1]);
}
