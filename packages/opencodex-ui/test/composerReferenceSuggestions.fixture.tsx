import { act, useLayoutEffect, type KeyboardEvent } from "react";
import { createRoot } from "react-dom/client";
import { LinkNode } from "@lexical/link";
import { $createParagraphNode, $createTextNode, $getRoot, $getSelection, $isRangeSelection, createEditor } from "lexical";
import { vi } from "vitest";
import type { OpenCodexFileSearchResult, OpenCodexSkillSearchResult } from "@open-codex-ui/opencodex-protocol";
import { serializeComposerContent } from "../src/components/chat/composerReferences";
import {
  useComposerReferenceSuggestions,
  type ComposerReferenceSuggestionsOptions as HookOptions,
  type ComposerReferenceSuggestionsState
} from "../src/components/chat/useComposerReferenceSuggestions";

/** Publishes committed hook state while letting React execute its real effects and cleanup. */
function SuggestionsHarness({ options, onState }: {
  options: HookOptions; onState(state: ComposerReferenceSuggestionsState): void;
}) {
  const state = useComposerReferenceSuggestions(options);
  useLayoutEffect(() => { onState(state); }, [state, onState]);
  return null;
}

/** Mounts a real hook and headless Lexical editor with controlled source-search callbacks. */
export function createSuggestionsFixture() {
  const editor = createEditor({ namespace: "reference-suggestions-test", nodes: [LinkNode], onError(error) { throw error; } });
  const onSearchFiles = vi.fn<HookOptions["onSearchFiles"]>().mockResolvedValue([]);
  const onSearchSkills = vi.fn<HookOptions["onSearchSkills"]>().mockResolvedValue([]);
  let options: HookOptions = { disabled: false, editorRef: { current: editor }, onSearchFiles, onSearchSkills };
  let state: ComposerReferenceSuggestionsState;
  const container = document.createElement("div");
  document.body.append(container);
  const root = createRoot(container);
  let isMounted = true;

  /** Captures committed state without substituting React or Lexical behavior. */
  function captureState(nextState: ComposerReferenceSuggestionsState): void { state = nextState; }

  /** Re-renders the hook after its configuration changes. */
  function render(): void {
    act(() => { root.render(<SuggestionsHarness options={options} onState={captureState} />); });
  }
  render();

  return {
    onSearchFiles,
    onSearchSkills,
    get state(): ComposerReferenceSuggestionsState { return state; },
    /** Sets a collapsed query selection in a real Lexical transaction. */
    setQuery(text: string, offset = text.length): void {
      act(() => {
        editor.update(() => {
          const node = $createTextNode(text);
          $getRoot().clear().append($createParagraphNode().append(node));
          node.select(offset, offset);
          state.updateFromEditor();
        }, { discrete: true });
      });
    },
    /** Rechecks the same trigger to model selection-only editor notifications. */
    refresh(): void {
      act(() => { editor.getEditorState().read(() => { state.updateFromEditor(); }); });
    },
    /** Sends the native key fields consumed by the hook's React event handler. */
    press(key: string): { handled: boolean; event: globalThis.KeyboardEvent } {
      const event = new window.KeyboardEvent("keydown", { key, cancelable: true });
      let handled = false;
      act(() => { handled = state.handleKeyDown(event as unknown as KeyboardEvent<HTMLDivElement>); });
      return { handled, event };
    },
    /** Commits a disabled-state update without replacing the editor or callbacks. */
    setDisabled(disabled: boolean): void {
      options = { ...options, disabled };
      render();
    },
    /** Reads the Markdown and structured references generated by the real editor. */
    serialize(): ReturnType<typeof serializeComposerContent> {
      return editor.getEditorState().read(serializeComposerContent);
    },
    /** Reads the caret after insertion to verify that subsequent typing follows the token. */
    readCaret(): { text: string; offset: number } | null {
      return editor.getEditorState().read(() => {
        const selection = $getSelection();
        if (!$isRangeSelection(selection)) return null;
        return { text: selection.anchor.getNode().getTextContent(), offset: selection.anchor.offset };
      });
    },
    /** Cancels pending effects and removes the fixture's mounted React root. */
    unmount(): void {
      if (!isMounted) return;
      act(() => { root.unmount(); });
      container.remove();
      isMounted = false;
    }
  };
}

/** Creates a deterministic source-relative file result. */
export function fileResult(fileName: string): OpenCodexFileSearchResult {
  return { root: "/repo", path: `/repo/src/${fileName}`, relativePath: `src/${fileName}`, fileName, matchType: "file" };
}

/** Creates a deterministic skill result with a stable source path. */
export function skillResult(): OpenCodexSkillSearchResult {
  return { name: "review", displayName: "Review", description: "Review code", shortDescription: null,
    path: "/repo/.agents/skills/review/SKILL.md", scope: "repo" };
}
